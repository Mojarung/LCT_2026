/** Очередь правок плана: следующая правка уходит на сервер только после ответа на предыдущую.
 *
 * Сервер применяет правку к плану в памяти без блокировки: две быстрые правки подряд читали
 * один и тот же план, и выживала одна (аудит 23.09: из 16 одновременных удалений терялось 14).
 * Пока на сервере блокировки нет, порядок держит клиент. Упавшая правка очередь не
 * останавливает: следующая уходит своим чередом. */
export class EditQueue {
  private tail: Promise<unknown> = Promise.resolve();

  enqueue<T>(task: () => Promise<T>): Promise<T> {
    const run = this.tail.then(task, task);
    this.tail = run.catch(() => undefined);
    return run;
  }
}
