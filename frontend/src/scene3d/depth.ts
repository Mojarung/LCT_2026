/* Ближняя плоскость камеры по высоте: без мерцания земли издалека.
 *
 * Точность буфера глубины падает как квадрат расстояния, делённый на ближнюю плоскость. При
 * постоянных 0,1 м с высоты нескольких сотен метров шаг глубины у дальнего края участка - метры,
 * и плоскость проезда (на ROAD_DROP_M ниже земли) просвечивала сквозь газон полосами. Ближняя
 * плоскость растёт с высотой камеры: 5 % высоты, а выше самых высоких объектов сцены
 * (TALL_M) - половина запаса над ними, но не дальше четверти высоты: ближе к камере, чем её
 * высота минус TALL_M, сцене нечего показать. У пешехода остаётся 0,1 м. */

export const MIN_NEAR_M = 0.1;
export const TALL_M = 120;

export function nearPlane(height: number): number {
  const y = Math.max(0, height);
  const wanted = Math.max(0.05 * y, 0.5 * (y - TALL_M));
  return Math.max(MIN_NEAR_M, Math.min(wanted, 0.25 * y));
}
