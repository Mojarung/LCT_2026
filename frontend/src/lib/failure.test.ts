import { describe, expect, it } from 'vitest';

import { explainFailure, firstSentence } from './failure';

describe('причина неудачи прогона словами человека', () => {
  it('новый текст сервиса: причина - его первая фраза, действие - про внешние ссылки', () => {
    const raw =
      'Чертёж прочитан не полностью: не найдены 4 внешние ссылки, у 12 объектов нет геометрии. ' +
      'Расчёт остановлен: сохраните DXF вместе с внешними ссылками. Подробности: XREF a; XREF b.';
    expect(explainFailure(raw)).toEqual({
      reason:
        'Чертёж прочитан не полностью: не найдены 4 внешние ссылки, у 12 объектов нет геометрии.',
      action: 'Пересохраните DXF вместе с внешними ссылками и запустите снова.',
      details: raw,
    });
  });

  it('старый текст неполного чертежа: ссылки сосчитаны по перечню, коды ушли в подробности', () => {
    const raw =
      'Неполная геометрия входного чертежа: XREF XREF_ИГДИ_Камчатская улица. Расчёт остановлен: ' +
      'загрузите внешние ссылки.';
    const failure = explainFailure(raw);
    expect(failure.reason).toBe('Чертёж прочитан не полностью: не найдена 1 внешняя ссылка.');
    expect(failure.details).toBe(raw);
  });

  it('без внешних ссылок совет - про неподдерживаемые объекты', () => {
    const raw =
      "Неполная геометрия входного чертежа: MESH, слой '0', блок 'b': 1 (unsupported), " +
      'примеры h:1. Расчёт остановлен.';
    const failure = explainFailure(raw);
    expect(failure.reason).toBe('Чертёж прочитан не полностью: у части объектов нет геометрии.');
    expect(failure.action).toBe(
      'Замените неподдерживаемые объекты полилиниями или штриховками, пересохраните DXF и запустите снова.',
    );
  });

  it('необработанное исключение не выдаёт имя класса за причину', () => {
    const failure = explainFailure("KeyError: 'utility.power_cable'");
    expect(failure.reason).toBe('Расчёт остановила внутренняя ошибка сервиса.');
    expect(failure.details).toBe("KeyError: 'utility.power_cable'");
  });

  it('незнакомая причина - первое предложение, остальное под раскрытием', () => {
    const raw = 'План не прошёл финальную проверку: 3 нарушения. Посадка № 4 у кабеля.';
    const failure = explainFailure(raw);
    expect(failure.reason).toBe('План не прошёл финальную проверку: 3 нарушения.');
    expect(failure.details).toBe(raw);
  });

  it('одна фраза - раскрывать нечего; пустая причина названа честно', () => {
    expect(explainFailure('Чертёж не читается: файл обрезан.').details).toBeNull();
    expect(explainFailure(null)).toEqual({
      reason: 'Сервис не записал причину.',
      action: 'Запустите прогон снова с консоли.',
      details: null,
    });
  });

  it('первое предложение не рвётся на сокращениях перед цифрой', () => {
    expect(firstSentence('До кабеля ближе нормы, п. 9.6 СП 42. Расчёт остановлен.')).toBe(
      'До кабеля ближе нормы, п. 9.6 СП 42.',
    );
  });
});
