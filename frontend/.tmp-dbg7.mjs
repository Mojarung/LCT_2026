import { chromium } from '@playwright/test';
const [out, view] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'chrome', args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
await p.goto(`http://localhost:5173/runs/01a0dccf-b370-7389-8cbf-b35ec61f502c/3d#view=${view}`);
await p.waitForFunction(() => window.__scene, null, { timeout: 240000 });
await p.waitForTimeout(8000);
await p.evaluate(() => window.__scene.apply({ utilities: true, boundary: true }));
await p.keyboard.press('h');
await p.waitForTimeout(1500);
await p.screenshot({ path: out });
await b.close();
